// Build 030: Shift + the step key under the cursor: on the shape page, that
// step's point out; then Shift let go (019-029: Shift + M4).
static void shift_step() {
    // Build 071 (step keys are the line's points): the key of the point at the cursor; with none there, a key
    // past the last point (the 16th: no line here holds 16 when this is used), which does nothing.
    const DraftLane& dl = page.draft().lanes[page.lane_index()];
    const i32 at = edit::find(dl, page.cursor());
    const u32 key = keys::step + (at >= 0 ? static_cast<u32>(at) % 16 : 15u);
    give(press(key, true));
    PageInput up = {};
    up.kind = PageInput::release, up.key = key, up.shift = true;
    give(up);
    up.key = keys::shift, up.shift = false;
    give(up);
}
